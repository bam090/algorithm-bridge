package bridge.greedy;

import java.util.Arrays;

/**
 * 그리디는 지금 할 수 있는 선택 가운데, 앞으로의 선택을 망치지 않는 한 가지를 고르는 방법이다.
 * 매번 가장 커 보이거나 가장 작아 보이는 값을 고른다고 모두 그리디가 되는 것은 아니다.
 * 왜 그 선택을 먼저 해도 최종 결과가 나빠지지 않는지 설명할 수 있어야 한다.
 * <p>
 * 눈앞에서 가장 커 보이는 값을 고르는 규칙도 작은 반례 하나에서 실패할 수 있다.
 * 선택 기준이 안전한 조건을 먼저 찾고, 그 조건이 문제 제약에 실제로 적혀 있는지 확인해야 한다.
 */
public final class GreedyGuide {

    private GreedyGuide() {
    }

    public static void main(String[] args) {
        int[] observations = {7, 1, 5};
        int[] ordered = observations.clone();
        Arrays.sort(ordered);

        System.out.println("[1] 복사본만 정렬하기");
        System.out.println("원본: " + Arrays.toString(observations));
        System.out.println("복사본: " + Arrays.toString(ordered));

        String[] labels = {"yellow", "red", "blue"};
        Arrays.sort(labels, (left, right) -> {
            int byLength = Integer.compare(left.length(), right.length());
            if (byLength != 0) {
                return byLength;
            }
            return left.compareTo(right);
        });

        System.out.println("\n[2] 주 기준과 동점 기준으로 정렬하기");
        System.out.println(Arrays.toString(labels));
    }

    /*
     * 그리디 선택이 안전한지 확인하는 순서
     *
     * 1) 무엇을 가장 많이, 가장 적게 또는 가장 빨리 만들려는지 확인한다.
     * 2) 지금 먼저 고를 기준을 한 문장으로 말한다.
     * 3) 작은 입력에서 그 기준이 실패하는 반례가 있는지 손으로 확인한다.
     * 4) 먼저 고른 선택을 다른 선택으로 바꾸어도 결과가 나빠지지 않는 이유를 설명한다.
     * 5) 이유를 설명할 수 있을 때만 그 기준으로 끝까지 반복한다.
     *
     * 예를 들어 목표 합을 넘지 않게 숫자를 고를 때 가장 큰 수부터 고르는 규칙은 항상 안전하지 않다.
     * 목표가 12이고 후보가 [10, 6, 6]이면 10을 먼저 고른 결과 10보다 6과 6을 고른 결과 12가 더 크다.
     * 이처럼 조건이 보장하지 않는 선택 기준은 그리디 규칙으로 사용하지 않는다.
     */

    /*
     * 문제에서 그리디를 떠올릴 단서
     *
     * - 필요한 선택 개수가 정해져 있고 비용 합을 가장 작게 만들어야 한다.
     * - 항목을 나눌 수 있어 단위당 비용이 낮은 부분부터 가져갈 수 있다.
     * - 두 값의 합이 정해진 하한과 상한 사이여야 한다.
     * - 같은 종류를 한꺼번에 선택해야 하며 큰 묶음이 목표를 빨리 채운다.
     * - 고정된 폭으로 빈 구간을 덮어야 한다.
     * - 목표에서 거꾸로 보면 비용 없는 직전 선택이 하나로 정해진다.
     *
     * 마지막 단서는 거꾸로 확인할 때 유용하다. 비용 없는 선택이 하나뿐이고 그 선택이
     * 나중의 유료 선택을 늘리지 않는다면 먼저 적용한다. 단순히 무료라는 이유만으로 고르지 말고,
     * 다른 선택을 먼저 해도 더 나은 결과가 나올 수 없는지 작은 반례로 확인한다.
     */

    /*
     * Java에서 자주 쓰는 도구
     *
     * - Arrays.copyOf(array, array.length): 원본을 보존할 복사본을 만든다.
     * - Arrays.sort(array): 작은 값부터 정렬한다.
     * - Integer.compare(a, b): a-b 대신 안전하게 두 정수를 비교한다.
     * - Map<K, Integer>: 종류별 개수를 기억한다.
     * - long: 여러 큰 비용이나 길이를 더할 때 int 넘침을 피한다.
     *
     * 비교자에서 right-left처럼 빼기로 순서를 정하면 큰 값에서 int가 넘칠 수 있다.
     * Integer.compare(right, left)처럼 비교 메서드를 사용한다.
     */

    /*
     * 주제별 선택 기준
     *
     * - 고를 개수가 정해진 최소 비용: 비용이 작은 항목부터 필요한 개수만큼 고른다.
     * - 나눌 수 있는 양의 최소 비용: 단위당 비용이 낮은 공급원부터 가져간다.
     * - 합의 허용 범위 안에서 최대 쌍: 양끝 합이 낮으면 왼쪽, 높으면 오른쪽을 움직인다.
     * - 출처 수 제한 안에서 목표 채우기: 빈도가 큰 그룹부터 누적하고 목표에 도달하면 멈춘다.
     * - 고정 폭으로 구간 덮기: 첫 번째 빈 위치부터 오른쪽을 최대한 덮는다.
     *
     * 조건이 달라지면 기준도 달라진다. 항목을 나눌 수 없으면 단위당 비용만 보고 고를 수 없고,
     * 합에 하한이 없다면 양끝에서 움직일 포인터를 고르는 이유도 달라진다.
     */

    /*
     * 작은 데이터 흐름을 확인하는 방법
     *
     * 값 [7, 1, 5]를 생각한다.
     * 1) clone()으로 서로 다른 배열 [7, 1, 5]를 만든다.
     * 2) 복사본만 정렬하면 [1, 5, 7]이 된다.
     * 3) 원본은 [7, 1, 5]로 그대로 남는다.
     * 4) 실제 문제에서는 이 정렬 결과를 어떤 선택에 쓸지 별도로 판단한다.
     */

    /*
     * 초보자가 자주 하는 실수
     *
     * - 가장 큰 값이나 가장 작은 값을 고르면 언제나 최적이라고 생각한다.
     * - 나눌 수 없는 항목에도 단위당 비용 기준을 사용한다.
     * - 정렬하면서 입력 배열까지 바꾼다.
     * - 비용 합계나 구간 끝을 int로 계산해 값이 넘친다.
     * - 동점일 때의 두 번째 기준을 정하지 않아 결과가 실행마다 달라진다.
     * - 첫 번째 빈 위치를 지나치거나 구간의 끝을 한 칸 더 덮는 실수를 한다.
     */

    /*
     * 코딩 테스트 문제를 읽는 확인 순서
     *
     * 1) 최종 목표는 개수, 비용, 가치, 선택 목록 중 무엇인가?
     * 2) 한 번 고른 선택을 나중에 취소할 수 있는가?
     * 3) 고를 개수가 정해져 있는가, 항목을 나눌 수 있는가?
     * 4) 지금 고른 선택이 나중 선택의 가능성을 얼마나 남기는가?
     * 5) 반례가 없는 안전 조건을 문제 제약에서 찾을 수 있는가?
     * 6) 정렬 원본, 합계 자료형, 동점과 구간 경계를 확인했는가?
     */
}
