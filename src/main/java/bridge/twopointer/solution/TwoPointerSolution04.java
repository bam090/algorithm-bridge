package bridge.twopointer.solution;

import java.util.Arrays;

/*
 * 정답 풀이: 한계 이하인 위치 쌍 세기
 *
 * 문제에서 발견해야 했던 단서
 * - 서로 다른 모든 위치 쌍 가운데 합 조건을 만족하는 개수를 구한다.
 * - 입력은 정렬되어 있지 않지만 원본은 바꾸면 안 된다.
 * - 한 위치는 서로 다른 여러 위치 쌍에 포함될 수 있다.
 *
 * 정렬과 양끝 포인터를 선택한 이유
 * 정렬하면 가장 작은 값과 현재 가장 큰 값의 합이 limit 이하일 때 그 사이의 값과 만든 합도 모두 조건을 만족한다.
 * 한 번의 비교로 여러 쌍을 세고, 합이 크면 가장 큰 값만 제외할 수 있다.
 *
 * 풀이 순서
 * 1. 원본을 복사해 오름차순으로 정렬한다.
 * 2. 왼쪽과 오른쪽을 양끝에 두고 쌍의 개수를 0으로 둔다.
 * 3. 현재 양끝 합을 계산한다.
 * 4. 합이 limit 이하면 왼쪽 값과 짝이 되는 남은 위치 수를 모두 더하고 왼쪽을 옮긴다.
 * 5. 합이 limit보다 크면 오른쪽을 옮겨 더 작은 합을 확인한다.
 * 6. 두 위치가 만나면 누적한 위치 쌍의 개수를 반환한다.
 *
 * 예시 데이터 흐름
 * [7, 1, 4, 2]를 정렬하면 [1, 2, 4, 7]이다.
 * 1+7은 6보다 크므로 오른쪽을 4로 옮긴다.
 * 1+4는 6 이하라 1과 2, 1과 4인 두 쌍을 한 번에 세고, 2+4인 한 쌍도 더해 3을 반환한다.
 *
 * 시간 복잡도: O(n log n), 복사본을 정렬한 뒤 양끝을 한 번씩 이동한다.
 * 공간 복잡도: O(n), 원본을 보존할 정렬 복사본이 필요하다.
 *
 * 초보자가 실수하기 쉬운 부분
 * - 조건을 만족할 때 한 쌍만 더해 중간에 있는 짝을 놓친다.
 * - 합이 limit보다 큰데 왼쪽을 옮겨 합을 더 크게 만든다.
 * - 같은 위치를 두 번 고르도록 left <= right까지 반복한다.
 * - 입력 배열을 직접 정렬한다.
 * - 최대 위치 쌍의 개수를 int에 저장한다.
 */
public final class TwoPointerSolution04 {

    private TwoPointerSolution04() {
    }

    public static long solve(int[] values, long limit) {
        // 정렬하면 가장 작은 값과 가장 큰 값의 합으로 사이 값들의 가능 여부도 함께 알 수 있다.
        // 양끝을 움직이면 모든 위치 쌍을 하나씩 만들지 않고 조건을 만족하는 묶음을 셀 수 있다.

        // [1] 원본을 복사해 오름차순으로 정렬한다.
        int[] ordered = values.clone();
        Arrays.sort(ordered);

        // [2] 왼쪽과 오른쪽을 양끝에 두고 쌍의 개수를 0으로 둔다.
        int left = 0;
        int right = ordered.length - 1;
        long pairCount = 0;

        while (left < right) {
            // [3] 현재 양끝 합을 계산한다.
            long sum = (long) ordered[left] + ordered[right];

            if (sum <= limit) {
                // [4] 합이 limit 이하면 왼쪽 값과 짝이 되는 남은 위치 수를 모두 더하고 왼쪽을 옮긴다.
                pairCount += right - left;
                left++;
            } else {
                // [5] 합이 limit보다 크면 오른쪽을 옮겨 더 작은 합을 확인한다.
                right--;
            }
        }

        // [6] 두 위치가 만나면 누적한 위치 쌍의 개수를 반환한다.
        return pairCount;
    }
}
